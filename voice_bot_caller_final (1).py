"""### Step 11 - Preview the scenario list

This prints each scenario number and name to know which index to pick for each call.
"""

for i, s in enumerate(scenarios): print(i, s['id'], s['name'])

"""## Part 4 - Voice pipeline

Here I prepare the listening component that decides when a speaker has started and stopped talking.

### Step 12 - Load voice activity detection

Silero detects when someone is speaking. The bot uses it to know when the agent has finished a sentence and when it is being interrupted. It is loaded once and reused for every call.
"""

vad = silero.VAD.load()

"""## Part 5 - Placing calls

Run these steps top to bottom for each scenario. To make the next call, change the index in Step 13 and run from there again. Listen to the first few recordings before running the rest and adjust the base prompt accordingly.

### Step 13 - Pick the scenario and name the room

Change the number inside the brackets to choose the scenario.
"""

scenario = scenarios[10]
room_name = f"call-{scenario['id']}-{int(time.time())}"

"""### Step 14 - Join the call room as the patient

This creates a pass for the bot and connects it to a private LiveKit room. The phone call will be placed into the same room in a later step.
"""

token = api.AccessToken(os.environ['LIVEKIT_API_KEY'], os.environ['LIVEKIT_API_SECRET']).with_identity('patient-bot').with_grants(api.VideoGrants(room_join=True, room=room_name)).to_jwt()
room = rtc.Room()
await room.connect(os.environ['LIVEKIT_URL'], token)

"""### Step 15 - Build the speech pipeline

This is the pipeline: Deepgram turns the agent's voice into text, the OpenAI model decides what the patient says next, and OpenAI text-to-speech speaks it. Each stage is separate, which keeps latency low and allows provider swap if need be.
"""

session = AgentSession(stt=deepgram.STT(model='nova-3'), llm=openai.LLM(model='gpt-4o-mini'), tts=openai.TTS(voice='alloy'), vad=vad, min_endpointing_delay=scenario['delay'])

"""### Step 16 - Give the bot its patient role

The agent combines the shared base prompt with the brief for this scenario.
"""

agent = Agent(instructions=BASE_PROMPT + scenario['brief'])

"""### Step 17 - Start the session

From here the bot is listening in the room and will talk as soon as the other side joins and speaks.
"""

import livekit.agents.utils.http_context

# Open the HTTP context and keep it open for the duration of the entire call
async with livekit.agents.utils.http_context.open():
    # 1. Start the agent session in the room
    await session.start(agent=agent, room=room)
    print("Bot started and listening...")

    # 2. Dial the target number
    TARGET_NUMBER == '+18054398008'
    print(f"Dialing {TARGET_NUMBER}...")
    call = await lkapi.sip.create_sip_participant(
        api.CreateSIPParticipantRequest(
            sip_trunk_id=trunk_id,
            sip_call_to=TARGET_NUMBER,
            room_name=room_name,
            participant_identity='clinic-agent',
            wait_until_answered=True
        )
    )
    call_start = time.time()
    print("Call connected! Waiting for conversation to finish...")

    # 3. Monitor the call until completion or timeout
    while room.remote_participants and time.time() - call_start < MAX_CALL_SECONDS:
        await asyncio.sleep(1)

    print("Call finished. Cleaning up...")

"""### Step 18 - Save the transcript

The session keeps a record of every spoken turn. This labels each line as the patient bot or the clinic agent.
"""

items = [i for i in session.history.items if i.type == 'message']
lines = [f"[{i.created_at - call_start:6.1f}s] {'PATIENT (bot)' if i.role == 'assistant' else 'CLINIC AGENT'}: {i.text_content}" for i in items]
pathlib.Path(f"transcripts/transcript-{scenario['id']}.txt").write_text(f"Scenario: {scenario['name']}\n" + '\n'.join(lines))

"""### Step 19 - Read the transcript

A quick look right after the call tells you whether the conversation was coherent.
"""

print(pathlib.Path(f"transcripts/transcript-{scenario['id']}.txt").read_text())

"""### Step 20 - Set up the Telnyx connection for the recording

Telnyx records the whole phone call with both sides on separate audio channels, based on the SIP connection recording settings.
"""

telnyx_headers = {'Authorization': 'Bearer ' + os.environ['TELNYX_API_KEY']}

"""### Step 21 - Wait for the recording to be ready

Telnyx needs a short time after hang up to finish processing the audio.
"""

await asyncio.sleep(25)

"""### Step 22 - Download the recording as mp3

Here the latest recordings are listed, and picks the newest one, downloads its mp3 and saves it with the same number as the transcript.
"""

recs = requests.get('https://api.telnyx.com/v2/recordings', headers=telnyx_headers, params={'page[size]': 5}).json().get('data', [])
if not recs:
    print("No recordings found. Please wait a bit longer and run this cell again.")
else:
    rec = max(recs, key=lambda r: r['created_at'])
    audio = requests.get(rec['download_urls']['mp3'])
    pathlib.Path(f"recordings/call-{scenario['id']}.mp3").write_bytes(audio.content)
    print("Recording downloaded successfully!")

"""### Step 23 - Check the file size

A recording of only a few kilobytes usually means the download failed or the call never connected.
"""

if 'audio' in locals():
    print(len(audio.content) // 1024, 'KB')
else:
    print("No recording downloaded yet. Please make sure the previous cell successfully downloads a recording first.")

"""### Step 24 - Hang up and close the room

Deleting the room makes sure the phone line is dropped even if the agent never hung up.
"""

await session.aclose()
await lkapi.room.delete_room(api.DeleteRoomRequest(room=room_name))

"""## Part 6 - Finding bugs in the agent

After all calls are saved, a language model reads each transcript and lists problems on the clinic agent's side.

### Step 25 - Create the OpenAI client

OpenAI LLM is used for the review. It reads the api keys I entered in Step 3.
"""

from openai import OpenAI
client = OpenAI()

"""### Step 26 - The reviewer instructions

The reviewer (OpenAI) is told to focus on useful, serious problems and to skip small wording nitpicks, because a short list of real bugs is worth more than a long list of trivia.
"""

ANALYST_PROMPT = 'You review a phone transcript between a simulated patient (PATIENT (bot)) and a medical office AI receptionist (CLINIC AGENT). Find real problems on the CLINIC AGENT side only: wrong or invented facts, confirming impossible or closed times, ignoring a request or compulsory patient confirmation check, leaking private information, unsafe handling of medical concerns, repeating itself in a loop, failing to confirm details, or confusing replies. Ignore punctuation and tiny speech-to-text errors. Return JSON only in this shape: {"bugs": [{"bug": "short title", "severity": "High, Medium or Low", "timestamp": "seconds from the line stamp", "details": "what happened and what should have happened"}]}. Return an empty list if the agent behaved well.'

"""### Step 27 - Load all transcripts

This reads every saved transcript into one dictionary keyed by file name.
"""

transcripts = {p.stem: p.read_text() for p in sorted(pathlib.Path('transcripts').glob('transcript-*.txt'))}

"""### Step 28 - Run the review on each call

Each transcript is sent to the model in turn and the JSON answer is stored under the same file name.
"""

reports = {}
for name, text in transcripts.items():
    reply = client.chat.completions.create(model='gpt-4o', response_format={'type': 'json_object'}, messages=[{'role': 'system', 'content': ANALYST_PROMPT}, {'role': 'user', 'content': text}])
    reports[name] = json.loads(reply.choices[0].message.content)

"""### Step 29 - Write the bug report

This turns the stored results into a readable markdown file with one entry per bug: title, severity, which transcript and when, and what went wrong.
"""

rows = [f"### {b['bug']}\n- Severity: {b['severity']}\n- Call: {name}.txt at {b['timestamp']}s\n- Details: {b['details']}\n" for name, r in reports.items() for b in r['bugs']]
pathlib.Path('bug_report.md').write_text('# Bug Report\n\n' + '\n'.join(rows))

"""### Step 30 - Read the bug report

Review the output, delete false alarms and sharpen the descriptions.
"""

print(pathlib.Path('bug_report.md').read_text())

