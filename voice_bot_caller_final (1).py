"""### Step 2 - Import the tools

This imports: the LiveKit room and API tools, the voice session classes, and the three provider plugins for speech-to-text, language model and text-to-speech.
"""

import os, asyncio, time, json, getpass, pathlib, requests
from livekit import rtc, api
from livekit.agents import AgentSession, Agent
from livekit.plugins import openai, deepgram, silero

"""### Step 3 - Load your keys

This asks for each key once and stores it only in the notebook's memory, so nothing secret is written into the file. If a key is already set in the environment it is reused. The LiveKit values are no longer typed into the notebook, so they are never saved in the notebook.
"""

keys = ['LIVEKIT_URL', 'LIVEKIT_API_KEY', 'LIVEKIT_API_SECRET', 'OPENAI_API_KEY', 'DEEPGRAM_API_KEY', 'TELNYX_API_KEY', 'TELNYX_PHONE_NUMBER', 'TELNYX_SIP_USER', 'TELNYX_SIP_PASS']
